"""Shared onboarding for divisions (`orche init`) and feature agents (`orche feat new`).

Steps: Orca worktree -> unit memory files (`.orche/<div|feat>/<name>/`) -> worktree
`.claude/settings.local.json` (merged) -> Entire's commit linking when the repository uses Entire
(`link_entire`) -> persona `.claude/agents/<session>.md` (rewritten when the
template's text differs; `hr/refresh.py` re-renders registered units) -> optional pane.
The caller writes the registry entry. Under dry-run every step prints its argv / target and
nothing is written; worktree paths are shown as `<name worktree>` placeholders.
"""
import json
import os
import shutil
import time
from pathlib import Path

from .. import log, orca, paths, registry, shell, templates, units, util, vendors
from ..cli import dry
from . import book, panes

PERSONAS = templates.TEMPLATES_ROOT / "personas"
SETTINGS_TMPL = templates.TEMPLATES_ROOT / "project" / ".claude" / "settings.local.json.tmpl"
PERSONA_HEADER = ("<!-- generated by ORCHE from templates/personas/{file}: orche init rewrites this file; "
                  "put project rules in .orche/STANDING.md -->")
ROLE_TEXT = {
    "division": "You run the {name} division of {project} as a long-lived owner of its charter.",
    "feature": "You own the {name} feature of {project}, inside its scope globs only.",
}


# Every ORCHE file in the repository: the whole `.orche/` (unit files, briefs and reports, the setup report),
# the shared `.claude/settings.local.json`, the units' personas (`.claude/agents/<session>.md`, session_name)
# and each file templates.copy_project puts outside `.orche/`.
EXCLUDE_LINES = (".orche/", units.SETTINGS_LOCAL, ".claude/agents/div-*.md", ".claude/agents/feat-*.md",
                 *(p.as_posix() for p in templates.project_files() if p.parts[0] != ".orche"))


class UnsafeTarget(Exception):
    """A write would land outside its worktree or inside the main checkout (exit 3)."""


def guard(target_dir, base, main_root=None) -> None:
    """Refuse when `target_dir` really resolves outside `base` (e.g. a `.claude` symlink).

    A target inside `base` is fine even when `base` is nested under `main_root`; one that
    resolves into the main checkout outside `base` is named as such in the refusal.
    """
    real = os.path.realpath(target_dir)
    if units.is_within(real, base):
        return
    if main_root and units.is_within(real, main_root):
        raise UnsafeTarget(f"{target_dir} resolves into the main checkout ({real}); refusing to write")
    raise UnsafeTarget(f"{target_dir} resolves to {real}, outside {base}; refusing to write")


def exclude_settings(worktree_dir, *, dry_run=False):
    """Add EXCLUDE_LINES (every ORCHE file) to the repository's shared `info/exclude` (each once). A file
    the project already committed stays tracked: git applies exclude to untracked files only.

    Returns (the exclude file path or None when the worktree is not a git checkout, wrote?).
    """
    return exclude_lines(worktree_dir, EXCLUDE_LINES, dry_run=dry_run)


def exclude_lines(worktree_dir, lines, *, dry_run=False):
    """Add each of `lines` (once) to the shared `info/exclude` of the checkout holding `worktree_dir`.

    Returns (the exclude file path or None when it is not a git checkout, wrote?).
    """
    if dry_run:
        dry(f"append {' '.join(lines)} to the info/exclude of {worktree_dir} (once)")
        return None, False
    res = shell.git(worktree_dir, "rev-parse", "--git-path", "info/exclude", timeout=30)
    if not res.ok or not res.out.strip():
        log.log("hr", f"info/exclude not updated: {worktree_dir} is not a git checkout")
        return None, False
    path = Path(res.out.strip())
    path = path if path.is_absolute() else Path(worktree_dir) / path
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    have = {ln.strip() for ln in text.splitlines()}
    missing = [ln for ln in lines if ln not in have]
    if not missing:
        return path, False
    sep = "" if not text or text.endswith("\n") else "\n"
    util.atomic_write(path, text + sep + "".join(f"{ln}\n" for ln in missing))
    return path, True


def parse_worktree(result, repo_id, name, fallback_branch):
    """(worktree id `<repoId>::<path>`, path, branch) from an `orca worktree create` result."""
    item = result.get("worktree", result) if isinstance(result, dict) else {}
    item = item if isinstance(item, dict) else {}
    path = item.get("path") or (item.get("git") or {}).get("path")
    if not path:
        raise orca.OrcaError(f"worktree create for {name} returned no path", "bad_output")
    wt_id = item.get("id") if "::" in str(item.get("id", "")) else f"{repo_id}::{path}"
    branch = str(item.get("branch") or (item.get("git") or {}).get("branch") or "")
    branch = branch.removeprefix("refs/heads/") or fallback_branch
    return wt_id, path, branch


def find_worktree(repo_id, name):
    """(id, path, branch) of an Orca worktree of `repo_id` already named `name`, else None."""
    try:
        result = orca.worktree("list")
    except orca.OrcaError as exc:
        log.log("hr", f"worktree list failed, creating {name} without the duplicate check: {exc}")
        return None
    items = result.get("worktrees") if isinstance(result, dict) else result
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, dict) or not item.get("path"):
            continue
        same_repo = item.get("repoId") == repo_id or str(item.get("id", "")).startswith(f"{repo_id}::")
        if same_repo and name in (item.get("displayName"), os.path.basename(str(item["path"]).rstrip("/"))):
            return parse_worktree(item, repo_id, name, "")
    return None


def create_worktree(repo_id, name, fallback_branch, *, parent=None, base=None, issue="", rename_to=None,
                    dry_run=False):
    """`orca worktree create`: from `origin/<base>` when the project's config names a base (else Orca's
    repo default), linked to the issue key (`--linear-issue KEY`, `--issue N` for `#N`) when there is one.
    `rename_to` (a feature's `<prefix>/<name>` when the project sets `publish.branch_prefix`): the branch
    Orca named is renamed to it right after creation; a failed rename keeps Orca's name (one log line)."""
    argv = ["--repo", f"id:{repo_id}", "--name", name]
    argv += ["--parent-worktree", f"id:{parent}"] if parent else ["--no-parent"]
    argv += ["--base-branch", f"origin/{base}"] if base else []
    argv += (["--issue", issue[1:]] if issue.startswith("#") else ["--linear-issue", issue]) if issue else []
    if dry_run:
        orca.worktree("create", *argv, dry_run=True)
        path = f"<{name} worktree>"
        return f"{repo_id}::{path}", path, fallback_branch
    wt_id, path, branch = parse_worktree(orca.worktree("create", *argv), repo_id, name, fallback_branch)
    if rename_to and branch != rename_to:
        res = shell.git(path, "branch", "-m", branch, rename_to, timeout=30)
        if res.ok:
            branch = rename_to
        else:
            log.log("hr", "branch rename failed: " + next((ln.strip() for ln in (res.err or res.out or "").splitlines()
                                                           if ln.strip()), f"exit {res.code}"))
    return wt_id, path, branch


def write_settings(worktree_dir, agent, *, main_root=None, dry_run=False) -> tuple:
    """Merge `{"agent", "crossSessionInbound"}` into the worktree's settings.local.json, writing only
    when the merged object differs. Returns (path, wrote?); a dry run says whether it would write."""
    target = Path(worktree_dir) / ".claude" / "settings.local.json"
    rendered = json.loads(templates.render(SETTINGS_TMPL.read_text(encoding="utf-8"), SESSION=agent))
    if dry_run:
        try:
            current = util.read_json(target, default=None)
        except (OSError, util.JsonError):
            current = None
        changed = not isinstance(current, dict) or {**current, **rendered} != current
        if changed:
            dry(f"write {target} agent={agent}")
        return target, changed
    guard(target.parent, worktree_dir, main_root)
    current = util.read_json(target, default={}) if target.exists() else {}
    if not isinstance(current, dict):
        raise util.JsonError(target, "not a JSON object")
    merged = {**current, **rendered}
    if target.exists() and merged == current:
        return target, False
    util.write_json(target, merged)
    return target, True


def link_entire(repo_root, worktree_dir, *, dry_run=False) -> tuple:
    """When the repository uses Entire (`<repo_root>/.entire/settings.json`, read live), make the worktree's
    `.entire/settings.local.json` hold `"commit_linking": "always"` (created as that one key; an existing
    file keeps its other keys; `.entire/settings.json` is never touched), so a worker's commits are linked
    to its session without a prompt. Entire gitignores the local file itself (`.entire/.gitignore`): nothing
    is committed. Returns (path or None when the repository does not use Entire, wrote?)."""
    from .. import detect
    if not detect.uses_entire(repo_root):
        return None, False
    target = Path(worktree_dir) / ".entire" / "settings.local.json"
    current = util.read_json(target, default={}) if target.exists() else {}
    if not isinstance(current, dict):
        raise util.JsonError(target, "not a JSON object")
    if current.get("commit_linking") == "always":
        return target, False
    if dry_run:
        dry(f"write {target} commit_linking=always")
        return target, True
    guard(target.parent, worktree_dir, repo_root)
    util.write_json(target, {**current, "commit_linking": "always"})
    return target, True


def persona_template(role, name, custom=False):
    """Most specific persona template that exists, else None. A custom division always uses the
    generic `div-custom.md`."""
    names = {"division": ["div-custom.md"] if custom else [f"div-{name}.md", "division.md"],
             "feature": ["feature.md"]}[role]
    return next((PERSONAS / n for n in names if (PERSONAS / n).is_file()), None)


def render_persona(tmpl, **vars) -> str:
    """Persona template `tmpl` rendered: first each `{{PART}}` line with the block every persona shares,
    `personas/parts/<part>.md`, then `vars` (so a `{{...}}` inside a value, e.g. a charter, stays as is)."""
    parts = {p.stem.upper(): templates.load(p) for p in sorted((PERSONAS / "parts").glob("*.md"))}
    return templates.render(templates.render(tmpl.read_text(encoding="utf-8"), **parts), **vars)


def _with_header(text, file) -> str:
    """`text` with PERSONA_HEADER as the line right after the frontmatter's closing `---` (on top
    when there is no frontmatter)."""
    header = PERSONA_HEADER.format(file=file) + "\n"
    lines = text.splitlines(keepends=True)
    if lines and lines[0].rstrip("\r\n") == "---":
        end = next((i for i in range(1, len(lines)) if lines[i].rstrip("\r\n") == "---"), None)
        if end is not None:
            return "".join(lines[:end + 1]) + header + "".join(lines[end + 1:])
    return header + text


def persona_text(role, *, project, name, session, model, effort, custom=None):
    """(persona text, rendered from a template?). `custom` = {"label", "charter"} of a custom division.
    A template-rendered persona carries PERSONA_HEADER right after its frontmatter. A Codex model
    renders `model: inherit` (the file stays a valid Claude Code agent; nothing starts Claude there)."""
    model = "inherit" if vendors.vendor_of(model) == vendors.CODEX else model
    tmpl = persona_template(role, name, custom=bool(custom))
    if tmpl is not None:
        extra = {"LABEL": custom["label"], "CHARTER": custom["charter"]} if custom else {}
        text = render_persona(tmpl, PROJECT=project, NAME=name, SESSION=session, MODEL=model, EFFORT=effort,
                              **extra)
        return _with_header(text, tmpl.name), True
    text = (f"---\nname: {session}\ndescription: ORCHE {role} agent for {project} ({name})\nmodel: {model}\n---\n"
            f"{ROLE_TEXT[role].format(name=name, project=project)}\n"
            + (f"Charter: {custom['charter']}\n" if custom else "")
            + "Read .orche/STANDING.md first; keep your HANDOFF.md current before any pause.\n")
    return text, False


def _read(path):
    """The text of `path`, or None when it is missing or unreadable."""
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def write_persona(dirs, agent, role, *, project, name, session, model, effort, main_root=None,
                  dry_run=False, custom=None, backup_dir=None) -> list:
    """Write `<dir>/.claude/agents/<agent>.md` into each of `dirs` when its text differs. Returns the
    paths written (a dry run: the paths it would write).

    Each target must resolve inside its own dir and, for dirs other than `main_root`, outside it.
    An existing file is first copied to `backup_dir/<agent>.<main|worktree>.md` when `backup_dir`
    is given.
    """
    text, from_template = persona_text(role, project=project, name=name, session=session, model=model,
                                       effort=effort, custom=custom)
    if not from_template and not dry_run:
        book.log(f"persona template missing for {role} {name}; wrote a minimal persona for {agent}")
    written = []
    for d in dirs:
        target = Path(d) / ".claude" / "agents" / f"{agent}.md"
        if dry_run:
            old = _read(target) if target.exists() else None
            if old is None:
                dry(f"write {target}" + ("" if from_template else " (minimal persona)"))
                written.append(target)
            elif from_template and old != text:
                dry(f"refresh {target}")
                written.append(target)
            continue
        own_main = main_root and os.path.realpath(d) == os.path.realpath(main_root)
        guard(target.parent, d, None if own_main else main_root)
        exists = target.exists()
        if exists and (not from_template or _read(target) == text):   # never a minimal persona over a file
            continue
        if exists and backup_dir is not None:
            backup = Path(backup_dir) / f"{agent}.{'main' if own_main else 'worktree'}.md"
            backup.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, backup)
        util.atomic_write(target, text)
        written.append(target)
    return written


def session_name(kind, key, name="") -> str:
    """The session of a unit or project pane (SPEC §14.8): div-<key>-<name>, feat-<key>-<name>,
    main-<key>."""
    return f"main-{key}" if kind == "main" else f"{kind}-{key}-{name}"


def session_owner(reg: dict, key: str, session: str):
    """The other project that has `session`, or reserves it, else None. Session names are unique
    registry-wide (Roster.member resolves a name to one member): another project holds every session
    it has (main, divisions, features, retired ones too) and reserves `div-<other>-<d>` for
    each standard division and each custom definition, onboarded or not."""
    for other, proj in reg.get("projects", {}).items():
        if other == key:
            continue
        held = {session_name("div", other, d) for d in (*registry.DIVISIONS, *(proj.get("custom_divisions") or {}))}
        if proj.get("main_session"):
            held.add(proj["main_session"])
        for div in (proj.get("divisions") or {}).values():
            held.update(s for s in [div.get("session")] + [f.get("session") for f in div.get("features", [])] if s)
        if session in held:
            return other
    return None


def write_project_marker(key, repo_root, *, dry_run):
    """`<repo>/.orche/project` = the project key (one line): the status line's fast path walks up to it.
    Returns (path, wrote?)."""
    marker = paths.project_local(repo_root) / "project"
    if dry_run:
        dry(f"write {marker} ({key})")
        return marker, False
    try:
        current = marker.read_text(encoding="utf-8") if marker.is_file() else None
    except OSError:
        current = None
    if current == key + "\n":
        return marker, False
    util.atomic_write(marker, key + "\n")
    return marker, True


def onboard(*, project, repo_root, repo_id, kind, name, model, effort, wake, parent=None, existing=None,
            on_created=None, dry_run=False, custom=None) -> dict:
    """Create one unit's worktree, files and (if `wake`) pane. Returns the partial registry entry.

    The session is session_name(kind, project, name), the worktree name `<kind>-<name>` and the
    branch the one Orca names (fallback `div/<name>` or, for a feature, `<prefix>/<name>`: publish.prefix,
    default `feat`); a feature of a project that sets `publish.branch_prefix` is renamed to `<prefix>/<name>`.
    `custom` ({"label", "charter"}) marks a custom division: its persona comes from `div-custom.md`.
    A persona it replaces is first copied to `ORCHE_HOME/backups/<project>/<ts>/` (as `orche init` does).
    `existing` (an `onboarding` registry entry) resumes: only the file steps and the pane run.
    Otherwise an Orca worktree already named `<kind>-<name>` is adopted, else one is created,
    and `on_created({"worktree", "branch"})` lets the caller save a provisional entry at once.
    """
    from .. import publish   # here, not at the top: hr stays free of the git/gh publish layer at import
    feature = kind == "feat"
    session, worktree_name = session_name(kind, project, name), f"{kind}-{name}"
    branch = f"{publish.prefix(None, project) if feature else kind}/{name}"
    configured = feature and bool(publish.settings(None, project).get("branch_prefix"))
    if existing:
        wt_id, branch = existing["worktree"], existing["branch"]
        wt_path = units.worktree_path(wt_id)
    else:
        found = None if dry_run else find_worktree(repo_id, worktree_name)
        if found:
            wt_id, wt_path, branch = found[0], found[1], found[2] or branch
        else:
            wt_id, wt_path, branch = create_worktree(
                repo_id, worktree_name, branch, parent=parent, base=publish.settings(None, project).get("base"),
                issue=publish.issue_of(name) if feature else "", rename_to=branch if configured else None,
                dry_run=dry_run)
    if not dry_run and units.is_within(repo_root, wt_path):
        raise orca.OrcaError(f"worktree for {name} resolved to the main checkout {wt_path}", "bad_output")
    if on_created and not existing and not dry_run:
        on_created({"worktree": wt_id, "branch": branch})
    unit_dir = Path(wt_path) / ".orche" / kind / name
    role = "division" if kind == "div" else "feature"
    if dry_run:
        dry(f"write {unit_dir}/{{{','.join(templates.UNIT_FILES)}}}")
    else:
        guard(unit_dir.parent, wt_path, repo_root)
        guard(unit_dir, wt_path, repo_root)
        templates.copy_unit(unit_dir, role, PROJECT=project, UNIT=name, SESSION=session)
    write_settings(wt_path, session, main_root=repo_root, dry_run=dry_run)
    link_entire(repo_root, wt_path, dry_run=dry_run)
    exclude_settings(wt_path, dry_run=dry_run)
    write_persona([repo_root, wt_path], session, role, project=project, name=name, session=session,
                  model=model, effort=effort, main_root=repo_root, dry_run=dry_run, custom=custom,
                  backup_dir=paths.orche_home() / "backups" / project / time.strftime("%Y%m%dT%H%M%S"))
    if wake:
        panes.open_pane(wt_id, session, panes.pane_command(session, resume=False), dry_run=dry_run)
    now = util.now_iso()
    return {"status": "active" if wake else "dormant", "worktree": wt_id, "branch": branch,
            "session": session, "model": model, "last_activity": now}
